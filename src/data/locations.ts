/**
 * Places the bot understands.
 *
 * This file only maps names to IANA timezone ids. It does not calculate the
 * clock. To add a place, add a place() entry. If two places share a name
 * (Georgia the country and Georgia the US state), do not give them the same
 * alias. Put that shared name in ambiguousAliases instead.
 */

export interface Location {
  id: string;
  name: string;
  aliases: readonly string[];
  timezone: string;
  countryCode?: string;
  representativeCity?: string;
  qualifier?: string;
  kind: 'country' | 'city' | 'region';
  /** Lower numbers show up first when autocomplete scores are tied. */
  rank?: number;
}

interface PlaceInput {
  id: string;
  name: string;
  timezone: string;
  kind: Location['kind'];
  aliases?: readonly string[];
  countryCode?: string;
  representativeCity?: string;
  qualifier?: string;
  rank?: number;
}

function place(input: PlaceInput): Location {
  return {
    id: input.id,
    name: input.name,
    timezone: input.timezone,
    kind: input.kind,
    aliases: input.aliases ?? [],
    ...(input.countryCode ? { countryCode: input.countryCode } : {}),
    ...(input.representativeCity ? { representativeCity: input.representativeCity } : {}),
    ...(input.qualifier ? { qualifier: input.qualifier } : {}),
    ...(input.rank !== undefined ? { rank: input.rank } : {}),
  };
}

